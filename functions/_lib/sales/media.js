/**
 * The player, or '' when the slot is empty. `label` names the video for a screen reader, since the
 * caption is optional and a bare <video> announces itself as nothing at all.
 */
export function mediaSlotHtml(media, slot, { label = '' } = {}) {
  const m = mediaSlot(media, slot);
  if (!m) return '';
  const e = escHtml;
  const ext = (m.url.split(/[?#]/)[0].split('.').pop() || '').toLowerCase();
  const type = VIDEO_TYPES[ext] ? ` type="${VIDEO_TYPES[ext]}"` : '';
  const aria = label || (MEDIA_SLOTS[slot] && MEDIA_SLOTS[slot].label) || 'Video';
  return `<figure class="vid">`
    + `<video controls playsinline preload="none"${m.poster ? ` poster="${e(m.poster)}"` : ''} aria-label="${e(aria)}">`
    + `<source src="${e(m.url)}"${type}>`
    + (m.captions_url ? `<track kind="captions" src="${e(m.captions_url)}" srclang="${e(m.captions_lang)}" label="${e(m.captions_label)}" default>` : '')
    + `<p class="fb">This browser cannot play the video. <a href="${e(m.url)}" rel="noopener">Open it in a new tab</a>.</p>`
    + `</video>`
    + (m.caption ? `<figcaption>${e(m.caption)}</figcaption>` : '')
    + `</figure>`;
}
