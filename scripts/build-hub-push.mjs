// Reproducible, checked-in Workers ESM bundle. Pages deploys functions without npm install.
// npm ci && npm run build:hub-push; check in the resulting vendor file with this source.
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
export const outputPath = resolve(root, 'functions/_lib/vendor/webcrypto-web-push.js');

export async function buildHubPush({ write = true } = {}) {
  const sources = [
    ['@block65/webcrypto-web-push', 'LICENSE.md'],
    ['uint8array-extras', 'license'],
  ];
  const notices = await Promise.all(sources.map(async ([name, licenseFile]) => {
    const dir = resolve(root, 'node_modules', name);
    const pkg = JSON.parse(await readFile(resolve(dir, 'package.json'), 'utf8'));
    const license = await readFile(resolve(dir, licenseFile), 'utf8');
    return `${name}@${pkg.version}\n${license.trim()}`;
  }));
  return build({
    absWorkingDir: root,
    stdin: { contents: 'export { buildPushPayload } from "@block65/webcrypto-web-push";', resolveDir: root, sourcefile: 'hub-push-vendor-entry.js' },
    bundle: true,
    platform: 'browser',
    format: 'esm',
    target: 'es2022',
    minify: false,
    legalComments: 'inline',
    banner: { js: `/*\nGenerated by scripts/build-hub-push.mjs — DO NOT EDIT.\nSource: https://github.com/block65/webcrypto-web-push\nSource: https://github.com/sindresorhus/uint8array-extras\n\n${notices.join('\n\n')}\n*/` },
    outfile: outputPath,
    write,
  });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildHubPush();
