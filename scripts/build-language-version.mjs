// Reproducible language-asset cache identity. Never imported by the Worker runtime.
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT=fileURLToPath(new URL('../',import.meta.url));
const OUTPUT='functions/_lib/language_asset_version.js';
const FILES=[
  'public/assets/js/i18n.js',
  'public/assets/js/public-i18n-coverage.js',
  'public/hub/assets/hub-i18n.js',
  'public/hub/assets/hub-i18n-coverage.js',
];

export async function buildLanguageVersion({root=ROOT,check=false}={}) {
  // Ordered UTF-8 path, NUL, original file bytes, NUL; no locale or timestamp input.
  const hash=createHash('sha256');
  for(const file of FILES){hash.update(file,'utf8');hash.update('\0');hash.update(await readFile(resolve(root,file)));hash.update('\0');}
  const revision='i18n-'+hash.digest('hex').slice(0,16);
  const source='// Generated by scripts/build-language-version.mjs. Do not edit.\n'+
    'export const LANGUAGE_ASSET_REVISION = '+JSON.stringify(revision)+';\n';
  const output=resolve(root,OUTPUT);
  if(check){
    let current;
    try{current=await readFile(output,'utf8');}catch{throw Error('Language asset fingerprint is missing. Run npm run build:language.');}
    if(current!==source)throw Error('Language asset fingerprint is stale. Run npm run build:language and commit the generated module.');
  }else await writeFile(output,source);
  return revision;
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const args=process.argv.slice(2);
  if(args.some(arg=>arg!=='--check'))throw Error('Usage: node scripts/build-language-version.mjs [--check]');
  console.log(await buildLanguageVersion({check:args.includes('--check')}));
}
