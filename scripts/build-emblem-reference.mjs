// Deterministic byte packaging only: never edits, resizes or replaces the approved PNG.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const source = 'public/assets/img/emblem.png';
const canonicalUrl = 'https://anejocateringco.com/assets/img/emblem.png';
const expectedHash = 'ee2072582d72f1cc2aadc21282dfc24bdce90d92bbf467a062defb6a5e799598';
const expectedBytes = 163850;
const bytes = readFileSync(new URL('../'+source, import.meta.url));
const hash = createHash('sha256').update(bytes).digest('hex');
if (bytes.length !== expectedBytes || hash !== expectedHash) throw Error('Canonical emblem changed; explicit reference review required before rebundling.');
const output = '// Generated by scripts/build-emblem-reference.mjs from the unchanged canonical PNG. Do not edit.\n' +
  'export const BUNDLED_EMBLEM_REFERENCE = Object.freeze(' + JSON.stringify({ source, canonical_url: canonicalUrl, sha256: hash, byte_length: bytes.length, data: bytes.toString('base64') }) + ');\n';
const target = new URL('../functions/_lib/generated_emblem_reference.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw Error('Emblem bundle differs; run node scripts/build-emblem-reference.mjs.');
  console.log('Canonical emblem bundle matches: '+bytes.length+' bytes, SHA256 '+hash);
} else {
  writeFileSync(target, output);
  console.log('Packaged unchanged canonical emblem: '+bytes.length+' bytes, SHA256 '+hash);
}
